import { createRequire } from 'node:module'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { execFile } from 'node:child_process'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const require = createRequire(import.meta.url)
const execFileAsync = promisify(execFile)
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const collectionsOutputPath = path.join(
  repoRoot,
  'src',
  'renderer',
  'src',
  'lib',
  'icons',
  'icon-collections.generated.ts'
)
const whitelistOutputPath = path.join(
  repoRoot,
  'src',
  'renderer',
  'src',
  'lib',
  'icons',
  'icon-whitelist.generated.ts'
)

const rendererRoots = [
  'src/renderer/src',
  'src/renderer/settings',
  'src/renderer/browser',
  'src/renderer/floating',
  'src/renderer/splash'
].map((sourcePath) => path.join(repoRoot, sourcePath))

const sourceExtensions = new Set(['.ts', '.tsx', '.vue', '.js', '.mjs'])
const iconPattern = /\b(lucide|vscode-icons|line-md):([a-z0-9][a-z0-9-]*)\b/g
const whitelist = {
  lucide: new Set(),
  'vscode-icons': new Set(),
  'line-md': new Set()
}

async function collectSourceFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const entryPath = path.join(dir, entry.name)
    if (entry.isDirectory()) {
      files.push(...(await collectSourceFiles(entryPath)))
      continue
    }

    if (entry.isFile() && sourceExtensions.has(path.extname(entry.name))) {
      files.push(entryPath)
    }
  }

  return files
}

function collectLiteralIcons(contents) {
  for (const match of contents.matchAll(iconPattern)) {
    whitelist[match[1]].add(match[2])
  }
}

function collectDeepChatAgentPickerIcons(contents) {
  const match = contents.match(/const\s+LUCIDE_ICONS\s*=\s*\[([\s\S]*?)\]/m)
  if (!match) {
    return
  }

  for (const iconMatch of match[1].matchAll(/['"]([a-z0-9][a-z0-9-]*)['"]/g)) {
    whitelist.lucide.add(iconMatch[1])
  }
}

function createSubsetCollection(collection, iconNames) {
  const icons = {}
  const aliases = {}

  for (const iconName of iconNames) {
    if (collection.icons?.[iconName]) {
      icons[iconName] = collection.icons[iconName]
      continue
    }

    if (collection.aliases?.[iconName]) {
      aliases[iconName] = collection.aliases[iconName]
    }
  }

  return {
    ...collection,
    icons,
    aliases
  }
}

function assertKnownIcons(collection, prefix, iconNames) {
  const missing = iconNames.filter(
    (iconName) => !collection.icons?.[iconName] && !collection.aliases?.[iconName]
  )

  if (missing.length > 0) {
    throw new Error(`Unknown ${prefix} icons: ${missing.join(', ')}`)
  }
}

function formatGeneratedWhitelist(generatedWhitelist) {
  return `/* eslint-disable */\n// Generated by scripts/generate-icon-collections.mjs. Do not edit by hand.\n\nexport type GeneratedIconCollectionKey = 'lucide' | 'vscodeIcons' | 'lineMd'\n\nexport const GENERATED_ICON_WHITELIST: Record<GeneratedIconCollectionKey, readonly string[]> = ${JSON.stringify(
    generatedWhitelist,
    null,
    2
  )} as const\n`
}

function formatGeneratedCollections(collections) {
  return `/* eslint-disable */\n// Generated by scripts/generate-icon-collections.mjs. Do not edit by hand.\n\nexport const lucideIconCollection = ${JSON.stringify(
    collections.lucide,
    null,
    2
  )} as const\n\nexport const vscodeIconCollection = ${JSON.stringify(
    collections.vscodeIcons,
    null,
    2
  )} as const\n\nexport const lineMdIconCollection = ${JSON.stringify(
    collections.lineMd,
    null,
    2
  )} as const\n`
}

async function formatGeneratedOutputs() {
  const oxfmtBin = path.join(repoRoot, 'node_modules', 'oxfmt', 'bin', 'oxfmt')

  await execFileAsync(process.execPath, [oxfmtBin, whitelistOutputPath, collectionsOutputPath], {
    cwd: repoRoot
  })
}

for (const sourceRoot of rendererRoots) {
  const files = await collectSourceFiles(sourceRoot)
  for (const file of files) {
    const contents = await readFile(file, 'utf8')
    collectLiteralIcons(contents)
    collectDeepChatAgentPickerIcons(contents)
  }
}

const lucideCollection = require('@iconify-json/lucide/icons.json')
const vscodeCollection = require('@iconify-json/vscode-icons/icons.json')
const lineMdCollection = require('../src/renderer/src/lib/icons/line-md-theme.json')

const lineMdIconNames = Object.keys(lineMdCollection.icons).sort()
for (const iconName of lineMdIconNames) {
  whitelist['line-md'].add(iconName)
}

const lucideIconNames = [...whitelist.lucide].sort()
const vscodeIconNames = [...whitelist['vscode-icons']].sort()
const generatedWhitelist = {
  lucide: lucideIconNames,
  vscodeIcons: vscodeIconNames,
  lineMd: [...whitelist['line-md']].sort()
}

assertKnownIcons(lucideCollection, 'lucide', generatedWhitelist.lucide)
assertKnownIcons(vscodeCollection, 'vscode-icons', generatedWhitelist.vscodeIcons)
assertKnownIcons(lineMdCollection, 'line-md', generatedWhitelist.lineMd)

const generatedCollections = {
  lucide: createSubsetCollection(lucideCollection, generatedWhitelist.lucide),
  vscodeIcons: createSubsetCollection(vscodeCollection, generatedWhitelist.vscodeIcons),
  lineMd: createSubsetCollection(lineMdCollection, generatedWhitelist.lineMd)
}

await Promise.all([
  writeFile(whitelistOutputPath, formatGeneratedWhitelist(generatedWhitelist)),
  writeFile(collectionsOutputPath, formatGeneratedCollections(generatedCollections))
])
await formatGeneratedOutputs()

console.info(
  `Generated icon collections: lucide=${generatedWhitelist.lucide.length}, vscode-icons=${generatedWhitelist.vscodeIcons.length}, line-md=${generatedWhitelist.lineMd.length}`
)
